"""Водитель — владелец дневника.

Идентификатор водителя разделяет дневники, но не защищает их: это не вход в систему. Кто
знает идентификатор, тот видит дневник. Настоящая авторизация заменила бы заголовок с
идентификатором на токен, а всё, что ниже API, осталось бы как есть.
"""

import re

#: Дневник запросов без заголовка `X-Driver-Id`: запросы из README и со страницы /docs
#: работают без подготовки. Сюда же попали поездки, записанные до появления водителей.
DEFAULT_DRIVER = "demo"

# Те же правила, что у `id` поездки: короткая строка без пробелов и служебных знаков.
_DRIVER_ID = re.compile(r"[A-Za-z0-9._:-]{1,64}")


def is_driver_id(text: str) -> bool:
    return _DRIVER_ID.fullmatch(text) is not None
